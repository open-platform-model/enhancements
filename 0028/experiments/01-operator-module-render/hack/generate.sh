#!/usr/bin/env bash
# Generate the module's CUE data files from the operator's controller-gen and
# kubebuilder YAML with `cue import` (never @embed: the kernel's sourcetree
# filter reads only .cue files).
#
#   hack/generate.sh                 # SRC=source (the copies in this dir)
#   SRC=/path/to/opm-operator/config CRD_SUBDIR=crd/bases hack/generate.sh
#   OUT=/tmp/x hack/generate.sh      # write elsewhere (drift-check uses this)
#
# Writes:
#   $OUT/zz_generated_crds.cue  #crdSource:  <crd name>:  <CRD object as imported>
#   $OUT/zz_generated_rbac.cue  #rbacSource: <unprefixed name>: <ClusterRole as imported>
set -euo pipefail

HERE=$(cd "$(dirname "$0")/.." && pwd)
SRC=${SRC:-$HERE/source}
CRD_SUBDIR=${CRD_SUBDIR:-crd}
RBAC_SUBDIR=${RBAC_SUBDIR:-rbac}
OUT=${OUT:-$HERE/module}
PKG=opm_operator

# The ClusterRole files the module carries: role.yaml is controller-gen
# output (+kubebuilder:rbac markers); the rest are kubebuilder scaffolds that
# ship unbound.
RBAC_FILES=(role.yaml metrics_reader_role.yaml moduleinstance_admin_role.yaml
	moduleinstance_editor_role.yaml moduleinstance_viewer_role.yaml
	transformerregistration_admin_role.yaml)

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# One multi-document stream per kind, in a stable (sorted) order.
for f in $(ls "$SRC/$CRD_SUBDIR"/*.yaml | sort); do
	printf -- '---\n' >>"$tmp/crds.yaml"
	cat "$f" >>"$tmp/crds.yaml"
done
for f in "${RBAC_FILES[@]}"; do
	printf -- '---\n' >>"$tmp/rbac.yaml"
	# Drop the YAML comment headers: they are prose, and cue import would
	# carry them as doc comments onto the first field.
	grep -v '^#' "$SRC/$RBAC_SUBDIR/$f" >>"$tmp/rbac.yaml"
done

header() {
	cat <<EOF
// Code generated by hack/generate.sh from $1 via cue import. DO NOT EDIT.
// Regenerate after 'make manifests' in opm-operator; hack/drift-check.sh fails
// when this file no longer matches its source YAML.

EOF
}

cue import -f -p "$PKG" -l '#crdSource:' -l 'metadata.name' -o "$tmp/crds.cue" "$tmp/crds.yaml"
cue import -f -p "$PKG" -l '#rbacSource:' -l 'metadata.name' -o "$tmp/rbac.cue" "$tmp/rbac.yaml"

{ header "$CRD_SUBDIR/*.yaml"; cat "$tmp/crds.cue"; } >"$tmp/crds.out"
{ header "the $RBAC_SUBDIR/ files in RBAC_FILES"; cat "$tmp/rbac.cue"; } >"$tmp/rbac.out"

cue fmt "$tmp/crds.out" "$tmp/rbac.out" 2>/dev/null || true
mkdir -p "$OUT"
cp "$tmp/crds.out" "$OUT/zz_generated_crds.cue"
cp "$tmp/rbac.out" "$OUT/zz_generated_rbac.cue"
echo "wrote $OUT/zz_generated_crds.cue $OUT/zz_generated_rbac.cue"
