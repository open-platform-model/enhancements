// instanceCUE is the #ModuleInstance for one render.
//
// Two things vary across the tree and nothing else does. metadata.name varies
// per RENDER index: it reaches every rendered resource's name and labels, so no
// render can be answered out of another render's evaluation state (the harness
// asserts consecutive digests differ). `values` varies per POINT: it is what
// makes a k=64 instance a 64-server fleet.
//
// The package name equals the directory name because CUE derives a package's
// name from the last element of its import path unless the import says
// otherwise, and these packages are imported by the generated render module.
func instanceCUE(p point, idx int) string {
	pkg := instPkg(p, idx)
	return fmt.Sprintf(`// GENERATED by the experiment 07 harness. Do not edit; edit gen.go.
package %s

import (
	c "opmodel.dev/core@v2"
	mod "experiments.opmodel.dev/0019/concurrent-render-at-scale/mods/%s"
)

instance: c.#ModuleInstance & {
	metadata: {
		name:      %q
		namespace: "default"
	}

	// The module enters by IMPORT, which is what keeps #config and #components
	// cross-references bound to the scope they were written in (experiment 04).
	#module: mod

	values: %s
}
`, pkg, p.modPkg(), fmt.Sprintf("%s-%d", p.Fixture, idx), valuesCUE(p))
}

func instPkg(p point, idx int) string   { return fmt.Sprintf("%s_n%03d", p.id(), idx) }
func renderPkg(p point, idx int) string { return "r_" + instPkg(p, idx) }

// valuesCUE is the per-point values body. Every entry differs from every other
// entry in the same instance (port, sizing, feature flags, settings), so a
// k=64 fleet is 64 different servers rather than one server evaluated 64 times.
func valuesCUE(p point) string {
	var b strings.Builder
	if p.Fixture == "fleet" {
		b.WriteString("{\n\t\tdomain: \"fleet.example.test\"\n\t\tservers: {\n")
		for i := 0; i < p.K; i++ {
			fmt.Fprintf(&b, "\t\t\t%s: {\n", serverName(i))
			fmt.Fprintf(&b, "\t\t\t\tenabled: %t\n", i%7 != 6)
			fmt.Fprintf(&b, "\t\t\t\tport:    %d\n", 25565+i)
			fmt.Fprintf(&b, "\t\t\t\tmemory:  %q\n", []string{"2Gi", "3Gi", "4Gi"}[i%3])
			fmt.Fprintf(&b, "\t\t\t\tmotd:    %q\n", fmt.Sprintf("welcome to %s", serverName(i)))
			fmt.Fprintf(&b, "\t\t\t\tstorage: {size: %q, storageClass: %q}\n",
				[]string{"8Gi", "16Gi", "32Gi"}[i%3], []string{"standard", "fast"}[i%2])
			// Emitted as an ORDERED slice, never a Go map. Field order in the
			// generated file is source order in CUE, and the fleet folds these
			// settings into a properties file with strings.Join, so a
			// randomised Go map iteration would hand the bp and raw variants
			// different bytes for a reason that has nothing to do with either.
			fmt.Fprintf(&b, "\t\t\t\tsettings: {\n")
			for _, kv := range [][2]string{
				{"max-players", fmt.Sprintf("%d", 20+i)},
				{"difficulty", []string{"peaceful", "easy", "normal", "hard"}[i%4]},
				{"view-distance", fmt.Sprintf("%d", 8+i%8)},
				{"pvp", fmt.Sprintf("%t", i%2 == 0)},
				{"level-seed", fmt.Sprintf("%d", 100000+i*7919)},
				{"motd", fmt.Sprintf("welcome to %s", serverName(i))},
			} {
				fmt.Fprintf(&b, "\t\t\t\t\t%q: %q\n", kv[0], kv[1])
			}
			b.WriteString("\t\t\t\t}\n\t\t\t}\n")
		}
		b.WriteString("\t\t}\n\t\trouter: {port: 25565, replicas: 2}\n\t}")
		return b.String()
	}

	runtimes := []string{"java", "node", "python", "go", "ruby"}
	b.WriteString("{\n\t\tservices: {\n")
	for i := 0; i < p.K; i++ {
		fmt.Fprintf(&b, "\t\t\t%s: {\n", serviceName(i))
		fmt.Fprintf(&b, "\t\t\t\truntime:     %q\n", runtimes[i%len(runtimes)])
		fmt.Fprintf(&b, "\t\t\t\tport:        %d\n", 8100+i)
		fmt.Fprintf(&b, "\t\t\t\tmetricsPort: %d\n", 9100+i)
		fmt.Fprintf(&b, "\t\t\t\tcpu:         %q\n", []string{"250m", "500m", "1000m"}[i%3])
		fmt.Fprintf(&b, "\t\t\t\tmemory:      %q\n", []string{"512Mi", "1Gi", "2Gi"}[i%3])
		fmt.Fprintf(&b, "\t\t\t\tstorage: {size: %q, storageClass: %q, cacheSize: %q}\n",
			[]string{"10Gi", "20Gi", "50Gi"}[i%3], []string{"standard", "fast"}[i%2],
			[]string{"512Mi", "1Gi"}[i%2])
		fmt.Fprintf(&b, "\t\t\t\tautoscale: {min: %d, max: %d, cpuTarget: %d}\n", 2+i%3, 10+i, 60+i%30)
		fmt.Fprintf(&b, "\t\t\t\tdisruption: minAvailable: %d\n", 1+i%2)
		// Every flag combination the guards can see, cycled so no two services
		// take the same path through the component body.
		fmt.Fprintf(&b, "\t\t\t\tfeatures: {metrics: %t, tracing: %t, cache: %t, tls: %t, profiling: %t, readOnly: %t}\n",
			i%2 == 0, i%3 == 0, i%2 == 1, i%4 == 0, i%5 == 0, i%3 != 2)
		fmt.Fprintf(&b, "\t\t\t\tenv: {\n")
		for _, kv := range [][2]string{
			{"LOG_LEVEL", []string{"info", "debug", "warn"}[i%3]},
			{"REGION", []string{"eu-north-1", "us-east-1"}[i%2]},
			{"SHARD", fmt.Sprintf("%d", i)},
			{"FEATURE_SET", fmt.Sprintf("set-%d", i%4)},
		} {
			fmt.Fprintf(&b, "\t\t\t\t\t%s: %q\n", kv[0], kv[1])
		}
		b.WriteString("\t\t\t\t}\n\t\t\t\tsettings: {\n")
		for j := 0; j < 10; j++ {
			fmt.Fprintf(&b, "\t\t\t\t\t%q: %q\n",
				fmt.Sprintf("key.%02d", j), fmt.Sprintf("value-%d-%d", i, j))
		}
		b.WriteString("\t\t\t\t}\n\t\t\t}\n")
	}
	b.WriteString("\t\t}\n\t}")
	return b.String()
}

// renderCUE is THE GLUE, execute-only.
//
// Copied from experiments/04-render-build-cost/fixtures/render/render.cue with
// one change: `_wanted` is emitted as a literal by the harness rather than
// hand-written, because it grows with the fixture. It is still a literal on the
// CUE side, so this glue does exactly what 04's did and no comprehension over
// components is added to the measured build.
//
// That the file grows with the module is not an artefact. In the proposed
// design the render module is generated per render by the kernel, so its size
// being a function of the module is a real property of the thing being costed.
func renderCUE(p point, idx int) string {
	return fmt.Sprintf(`// GENERATED by the experiment 07 harness. Do not edit; edit gen.go.
//
// THE GLUE, execute-only. Copied from experiment 04's render.cue: the match
// phase is absent on purpose (experiment 05 owns what matching costs), and the
// platform is interposed so the transformer map arrives through the platform
// (D5) rather than by importing the catalog directly.
package render

import (
	inst "experiments.opmodel.dev/0019/concurrent-render-at-scale/mods/i/%s"
	platform "experiments.opmodel.dev/0019/concurrent-render-at-scale/platform@v0"
)

_transformers: platform.#composedTransformers

instance:   inst.instance
components: instance.components

// Pair selection, which is NOT matching: transformers are named by SHORT NAME
// and located by a key lookup, so no version is restated as data and a catalog
// bump fails loudly (an unmatched name yields no pair and the output count
// assertion fires) rather than quietly changing which bodies execute.
_wanted: %s

pairs: [
	for cid, names in _wanted
	for n in names
	for fqn, _ in _transformers
	if fqn =~ "/\(n)@" {{component: cid, transformer: fqn}},
]

// #context, as a projection over the other two inputs (OQ5).
_contextFor: {
	comp!: _
	out: {
		#moduleInstanceMetadata: {
			name:      instance.metadata.name
			namespace: instance.metadata.namespace
			fqn:       instance.metadata.fqn
			uuid:      instance.metadata.uuid
			version:   instance.#moduleMetadata.version
			if instance.metadata.labels != _|_ {labels: instance.metadata.labels}
			if instance.metadata.annotations != _|_ {annotations: instance.metadata.annotations}
		}
		#componentMetadata: {
			name: comp.metadata.name
			if comp.metadata.labels != _|_ {labels: comp.metadata.labels}
			if comp.metadata.annotations != _|_ {annotations: comp.metadata.annotations}
		}
		#runtimeName: "concurrent-render-at-scale"
	}
}

// Execute: one unification per pair, all three declared inputs supplied,
// nothing stripped.
rendered: {
	for p in pairs {
		"\(p.component) :: \(p.transformer)": (_transformers[p.transformer].#transform & {
			#moduleInstance: instance
			#component:      components[p.component]
			#context:        (_contextFor & {comp: components[p.component]}).out
		}).output
	}
}
`, instPkg(p, idx), wantedCUE(p))
}

func wantedCUE(p point) string {
	w := p.wants()
	keys := make([]string, 0, len(w))
	for k := range w {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("{\n")
	for _, k := range keys {
		quoted := make([]string, len(w[k]))
		for i, n := range w[k] {
			quoted[i] = fmt.Sprintf("%q", n)
		}
		fmt.Fprintf(&b, "\t%q: [%s]\n", k, strings.Join(quoted, ", "))
	}
	b.WriteString("}")
	return b.String()
}
