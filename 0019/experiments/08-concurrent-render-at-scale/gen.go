// ---------------------------------------------------------------------------
// A point in the sweep
// ---------------------------------------------------------------------------

// point is one measurement cell: which fixture, authored which way, at which
// size. Every point is rendered by both arms, so the single-build / baseline
// ratio is available at every size rather than only at the one 04 measured.
type point struct {
	Fixture string // "fleet" (breadth) or "complex" (depth)
	Style   string // "bp" (blueprint) or "raw" (resources and traits)
	K       int    // components: fleet servers + 1 router, or complex services
}

func (p point) id() string {
	return fmt.Sprintf("%s_%s_k%03d", p.Fixture, p.Style, p.K)
}

// modPkg is the fixture module package this point's instance imports.
func (p point) modPkg() string { return p.Fixture + "_" + p.Style }

// components is the number of components the instance produces.
func (p point) components() int {
	if p.Fixture == "fleet" {
		return p.K + 1 // K servers plus the aggregating router
	}
	return p.K
}

// outputs is the number of (component, transformer) pairs the render must
// produce. Asserted on every sample: an empty `rendered` evaluates instantly,
// so without the assertion a point that silently rendered nothing would report
// as the cheapest one.
func (p point) outputs() int {
	n := 0
	for _, names := range p.wants() {
		n += len(names)
	}
	return n
}

// wants is the (component -> transformer short name) selection, used verbatim
// by BOTH arms: the CUE glue gets it as a literal map, and the baseline arm
// resolves the same short names against the held transformer map. It is a
// LOOKUP, not matching. Nothing here reads a component's #resources, #traits or
// matchLabels; experiment 05 owns what real matching costs, and folding it in
// would make every number below a sum of two unknowns.
func (p point) wants() map[string][]string {
	out := map[string][]string{}
	if p.Fixture == "fleet" {
		for i := 0; i < p.K; i++ {
			out["server-"+serverName(i)] = []string{
				"statefulset-transformer", "service-transformer", "configmap-transformer",
			}
		}
		out["router"] = []string{
			"deployment-transformer", "service-transformer", "http-route-transformer",
		}
		return out
	}
	for i := 0; i < p.K; i++ {
		out[serviceName(i)] = []string{
			"statefulset-transformer", "service-transformer", "configmap-transformer",
			"pdb-transformer", "hpa-transformer",
		}
	}
	return out
}

func serverName(i int) string  { return fmt.Sprintf("s%03d", i) }
func serviceName(i int) string { return fmt.Sprintf("svc%03d", i) }

