// fixtureRepo is a small repo that holds every shape of citation. The
// numbers are built in pieces so that this file passes cite-lint itself.
var fixtureRepo = map[string]string{
	"src/a.go":          "package a\n\n// Rejects the second write (0010:D11).\n// The 0010:D34 ladder decides the level.\nvar x = 1\n\n// 0010:D4\nvar y = 2\n\nvar s = \"retired (0006:D21)\"\n",
	"src/b.cue":         "// WHY fqn: 0010:D49.\n// Experimental (v1alpha1 contracts, 0010 D34).\n// Open until the vote (0014:OQ2).\nx: 1\n",
	"src/c.go":          "package a\n\n/* Rejects the write\n * and says why (enhancement 0010 D4 and D7, 0011 D3/D15).\n */\nvar z = 3\n",
	"src/gen.go":        "// Code generated by x. DO NOT EDIT.\n\npackage a\n\n// Rejects the write (0010:D11).\nvar g = 1\n",
	"src/tmpl.cue.tmpl": "// Renders the build (enhancement 0019 D5).\nx: 1\n",
	"docs/a.md":         "# Doc\n\nThe key decides (0010:D4). Per 0030:D4, the graph is read only.\n\n```cue\n// (0010:D4)\n```\n\nSee `enhancements/0010` and 0014:OQ2.\n",
	"docs/b.yaml":       "# keep it (0010:D4)\nrule: \"keep the key (0010:D4)\"\n",
	"openspec/changes/archive/2026-01-01-x/proposal.md":      "Delivers the key (0010 D4, 0011:D3).\n",
	"openspec/changes/archive/2026-01-01-x/enhancement.yaml": "enhancement: \"0010\"\n",
	"openspec/changes/active/proposal.md":                    "Keeps the key (0010:D4).\n",
	"tests/fixtures/f.cue":                                   "// Keeps the key (0010:D4).\nx: 1\n",
	"CHANGELOG.md":                                           "- fix (0010:D4)\n",
	"vendor/v.go":                                            "package v\n\n// Keeps the key (0010:D4).\n",
}

func TestWriteThenLint(t *testing.T) {
	root := t.TempDir()
	for rel, body := range fixtureRepo {
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	excl := []string{"tests/fixtures/", "openspec/changes/active/"}
	rep, err := Run(Options{Root: root, Exclude: excl, Write: true})
	if err != nil {
		t.Fatal(err)
	}

	// cite-lint reports only the sites of the worklist.
	res, err := citelint.LintFiles(root, []string{"."}, citelint.Options{Exclude: excl})
	if err != nil {
		t.Fatal(err)
	}
	lint := map[string]bool{}
	for _, f := range res.Findings {
		lint[fmt.Sprintf("%s:%d", f.Path, f.Line)] = true
	}
	list := map[string]bool{}
	for _, s := range rep.Sites {
		list[fmt.Sprintf("%s:%d", s.Path, s.Line)] = true
	}
	var extra []string
	for k := range lint {
		if !list[k] {
			extra = append(extra, k)
		}
	}
	sort.Strings(extra)
	if len(extra) > 0 {
		t.Errorf("cite-lint finds sites that the worklist does not list: %v", extra)
	}
	if len(lint) == 0 {
		t.Error("the fixture holds sites that cite-lint must still find")
	}

	// What was rewritten reads right.
	a, _ := os.ReadFile(filepath.Join(root, "src/a.go"))
	if !strings.Contains(string(a), "// Rejects the second write (enhancement 0010).") {
		t.Errorf("src/a.go:\n%s", a)
	}
	c, _ := os.ReadFile(filepath.Join(root, "src/c.go"))
	if !strings.Contains(string(c), "and says why (enhancements 0010 and 0011).") {
		t.Errorf("src/c.go:\n%s", c)
	}
	md, _ := os.ReadFile(filepath.Join(root, "docs/a.md"))
	if !strings.Contains(string(md), "Per 0030:D4, the graph is read only.") {
		t.Errorf("docs/a.md:\n%s", md)
	}
	// Excluded and skipped files are as they were.
	for _, rel := range []string{"tests/fixtures/f.cue", "openspec/changes/active/proposal.md", "CHANGELOG.md", "vendor/v.go", "src/gen.go"} {
		b, _ := os.ReadFile(filepath.Join(root, rel))
		if string(b) != fixtureRepo[rel] {
			t.Errorf("%s changed:\n%s", rel, b)
		}
	}
	if _, err := os.Stat(filepath.Join(root, "openspec/changes/archive/2026-01-01-x/enhancement.yaml")); err == nil {
		t.Error("enhancement.yaml was not deleted")
	}

	// A second write changes nothing and lists the same sites.
	again, err := Run(Options{Root: root, Exclude: excl, Write: true})
	if err != nil || len(again.Changed) != 0 || len(again.Deleted) != 0 {
		t.Fatalf("second write: changed %v deleted %v err %v", again.Changed, again.Deleted, err)
	}
	if len(again.Sites) != len(rep.Sites) {
		t.Errorf("the worklist moved: %d then %d rows", len(rep.Sites), len(again.Sites))
	}
}

func TestWorklistFile(t *testing.T) {
	rep := &Report{Sites: []Site{{Path: "a.go", Line: 3, Kind: KindInline, Text: "a\tb", Title: "0010 D4: t"}}}
	var b strings.Builder
	if err := rep.WriteWorklist(&b); err != nil {
		t.Fatal(err)
	}
	want := "path\tline\tkind\ttext\ttitle\na.go\t3\tinline\ta b\t0010 D4: t\n"
	if b.String() != want {
		t.Errorf("got %q want %q", b.String(), want)
	}
}

// --generated marks paths as generated: only listed, never written.
func TestGeneratedPaths(t *testing.T) {
	root := t.TempDir()
	body := "# there is no range (0010:D14)\nkey: value\n"
	for _, rel := range []string{"config/crd/bases/a.yaml", "dist/install.yaml", "docs/b.yaml"} {
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	rep, err := Run(Options{Root: root, Write: true, Generated: []string{"config/crd/bases/", "dist/"}})
	if err != nil {
		t.Fatal(err)
	}
	if len(rep.Changed) != 1 || rep.Changed[0] != "docs/b.yaml" {
		t.Errorf("changed %v, want only docs/b.yaml", rep.Changed)
	}
	kinds := map[string]string{}
	for _, s := range rep.Sites {
		kinds[s.Path] = s.Kind
	}
	if kinds["config/crd/bases/a.yaml"] != KindGenerated || kinds["dist/install.yaml"] != KindGenerated || len(rep.Sites) != 2 {
		t.Errorf("sites %+v", rep.Sites)
	}
	for _, rel := range []string{"config/crd/bases/a.yaml", "dist/install.yaml"} {
		b, _ := os.ReadFile(filepath.Join(root, rel))
		if string(b) != body {
			t.Errorf("%s was written: %q", rel, b)
		}
	}
}
