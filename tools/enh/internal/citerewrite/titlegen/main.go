// Command titlegen builds titles.tsv, the table of decision titles that
// cite-rewrite quotes. It reads the decision headings of the 27 entries at one
// commit of the enhancements repo:
//
//	NNNN/03-decisions.md and archive/NNNN/03-decisions.md, "### Dn: <title>"
//
// Usage (the go:generate line in titles.go runs it):
//
//	go run ./titlegen -ref 18705155 -out titles.tsv
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var (
	pathRe    = regexp.MustCompile(`^(archive/)?(\d{4})/03-decisions\.md$`)
	headingRe = regexp.MustCompile(`^### D(\d+): (.+?)\s*$`)
)

type row struct {
	id     string
	n      int
	layout string
	title  string
}

func git(repo string, args ...string) (string, error) {
	cmd := exec.Command("git", append([]string{"-C", repo}, args...)...)
	out, err := cmd.Output()
	return string(out), err
}

func main() {
	repo := flag.String("repo", "", "the enhancements checkout (default: the repo of the current directory)")
	ref := flag.String("ref", "", "the commit that holds the decision files, before the migration")
	outPath := flag.String("out", "titles.tsv", "the file to write")
	flag.Parse()
	if *ref == "" {
		fmt.Fprintln(os.Stderr, "titlegen: -ref is required")
		os.Exit(2)
	}
	if *repo == "" {
		top, err := git(".", "rev-parse", "--show-toplevel")
		if err != nil {
			fmt.Fprintln(os.Stderr, "titlegen:", err)
			os.Exit(2)
		}
		*repo = strings.TrimSpace(top)
	}
	list, err := git(*repo, "ls-tree", "-r", "--name-only", *ref)
	if err != nil {
		fmt.Fprintln(os.Stderr, "titlegen:", err)
		os.Exit(2)
	}
	var rows []row
	entries := map[string]bool{}
	for _, p := range strings.Split(list, "\n") {
		m := pathRe.FindStringSubmatch(p)
		if m == nil || m[2] == "0000" {
			// 0000 is the template folder, not an entry.
			continue
		}
		layout := "live"
		if m[1] != "" {
			layout = "archived"
		}
		body, err := git(*repo, "show", *ref+":"+p)
		if err != nil {
			fmt.Fprintln(os.Stderr, "titlegen:", err)
			os.Exit(2)
		}
		entries[m[2]] = true
		for _, line := range strings.Split(body, "\n") {
			h := headingRe.FindStringSubmatch(line)
			if h == nil {
				continue
			}
			n, _ := strconv.Atoi(h[1])
			title := strings.Join(strings.Fields(h[2]), " ")
			rows = append(rows, row{m[2], n, layout, title})
		}
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].id != rows[j].id {
			return rows[i].id < rows[j].id
		}
		return rows[i].n < rows[j].n
	})
	f, err := os.Create(*outPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "titlegen:", err)
		os.Exit(2)
	}
	w := bufio.NewWriter(f)
	fmt.Fprintf(w, "# Decision titles of the %d entries at %s: id, decision number, layout, title.\n", len(entries), *ref)
	fmt.Fprintln(w, "# Generated by titlegen (go generate ./internal/citerewrite). Do not edit by hand.")
	for _, r := range rows {
		fmt.Fprintf(w, "%s\t%d\t%s\t%s\n", r.id, r.n, r.layout, r.title)
	}
	if err := w.Flush(); err != nil {
		fmt.Fprintln(os.Stderr, "titlegen:", err)
		os.Exit(2)
	}
	if err := f.Close(); err != nil {
		fmt.Fprintln(os.Stderr, "titlegen:", err)
		os.Exit(2)
	}
	fmt.Printf("titlegen: %d entries, %d decisions at %s\n", len(entries), len(rows), *ref)
}
