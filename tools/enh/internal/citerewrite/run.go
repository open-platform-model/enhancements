// Options tunes a run.
type Options struct {
	// Root is the repo; Paths are relative to it (default: the root).
	Root  string
	Paths []string
	// Exclude holds the patterns of cite-lint's --exclude.
	Exclude []string
	// Write applies the edits; without it nothing changes.
	Write  bool
	Titles *Titles
	// Generated holds more paths (files, folders, base names) that are
	// generated: their citations are worklist rows of kind generated.
	Generated []string
}

// Report is the outcome of a run.
type Report struct {
	// Files counts the files read; Skipped the files left out.
	Files, Skipped int
	// Changed lists the files with at least one edit; Deleted the
	// enhancement.yaml files.
	Changed, Deleted []string
	// Edits counts the edits by place and form.
	Edits map[string]map[Form]int
	// Sites is the worklist.
	Sites []Site
}

// Process reads one file and returns its edits and worklist rows.
func Process(name string, src []byte, tt *Titles) FileResult {
	return process(name, src, tt, false)
}

func process(name string, src []byte, tt *Titles, generated bool) FileResult {
	if generated || isGeneratedFile(name, src) {
		c := newCtx(name, src, tt)
		for ln := 1; ln <= len(c.li.starts); ln++ {
			c.lineSites(c.li.text(ln), c.li.starts[ln-1], KindGenerated)
		}
		return c.res
	}
	lower := strings.ToLower(name)
	switch {
	case citelint.IsCode(name):
		return processCode(name, src, tt)
	case strings.HasSuffix(lower, ".md"), strings.HasSuffix(lower, ".markdown"):
		return processText(name, src, tt, textMarkdown)
	case strings.HasSuffix(lower, ".yaml"), strings.HasSuffix(lower, ".yml"):
		return processText(name, src, tt, textYAML)
	case strings.HasSuffix(lower, ".sh"), strings.HasSuffix(lower, ".bash"):
		return processText(name, src, tt, textHash)
	}
	c := newCtx(name, src, tt)
	for ln := 1; ln <= len(c.li.starts); ln++ {
		c.lineSites(c.li.text(ln), c.li.starts[ln-1], KindOtherFile)
	}
	return c.res
}

var goHeaderRe = regexp.MustCompile(`(?m)^// Code generated .* DO NOT EDIT\.\r?$`)

// isGeneratedFile reports whether a file is generated. Only these count: Go's
// exact "// Code generated ... DO NOT EDIT." line near the top of any file, a
// generator's file name (zz_generated, .pb.go, _gen.go), and the controller-gen
// annotation in a YAML or JSON data file. A word in prose ("generated by the
// frontend") never marks a file: hand-written files say such things. More
// paths come from --generated.
func isGeneratedFile(name string, src []byte) bool {
	base := path.Base(filepath.ToSlash(name))
	if strings.HasPrefix(base, "zz_generated") || strings.HasSuffix(base, ".pb.go") || strings.HasSuffix(base, "_gen.go") {
		return true
	}
	if citelint.IsGo(name) && citelint.IsGeneratedSource(src) {
		return true
	}
	head := src
	if len(head) > 4000 {
		head = head[:4000]
	}
	lines := strings.Split(string(head), "\n")
	if len(lines) > 12 {
		lines = lines[:12]
	}
	if goHeaderRe.MatchString(strings.Join(lines, "\n")) {
		return true
	}
	lower := strings.ToLower(base)
	if strings.HasSuffix(lower, ".yaml") || strings.HasSuffix(lower, ".yml") || strings.HasSuffix(lower, ".json") {
		for i, l := range strings.Split(string(head), "\n") {
			if i < 40 && strings.Contains(l, "controller-gen.kubebuilder.io/version") {
				return true
			}
		}
	}
	return false
}

func placeOf(rel string) string {
	switch {
	case strings.HasPrefix(rel, "openspec/changes/archive/") || strings.Contains(rel, "/openspec/changes/archive/"):
		return "archived"
	case strings.HasPrefix(rel, "openspec/specs/") || strings.Contains(rel, "/openspec/specs/"):
		return "live-spec"
	case strings.HasPrefix(rel, "openspec/changes/"):
		return "active-change"
	case citelint.IsCode(rel):
		return "code"
	case strings.HasSuffix(rel, ".md"):
		return "docs"
	}
	return "other"
}

// Run walks the paths and applies the rewrite in the mode of the options.
func Run(opts Options) (*Report, error) {
	if opts.Titles == nil {
		opts.Titles = DefaultTitles()
	}
	rep := &Report{Edits: map[string]map[Form]int{}}
	var errs []error

	one := func(rel string) {
		under := citelint.UnderRoot(opts.Root, rel)
		if citelint.Excluded(under, opts.Exclude) || citelint.Skipped(under) {
			rep.Skipped++
			return
		}
		full := rel
		if !filepath.IsAbs(rel) {
			full = filepath.Join(opts.Root, rel)
		}
		name := filepath.ToSlash(under)
		if path.Base(name) == "enhancement.yaml" {
			rep.Files++
			rep.Deleted = append(rep.Deleted, name)
			rep.bump(placeOf(name), FormDelete, 1)
			if opts.Write {
				if err := os.Remove(full); err != nil {
					errs = append(errs, err)
				}
			}
			return
		}
		info, err := os.Lstat(full)
		if err != nil {
			errs = append(errs, err)
			return
		}
		if !info.Mode().IsRegular() || info.Size() > 4<<20 {
			rep.Skipped++
			return
		}
		src, err := os.ReadFile(full)
		if err != nil {
			errs = append(errs, err)
			return
		}
		if bytes.IndexByte(src, 0) >= 0 {
			rep.Skipped++
			return
		}
		rep.Files++
		gen := citelint.Excluded(under, opts.Generated)
		res := process(name, src, opts.Titles, gen)
		rep.Sites = append(rep.Sites, res.Sites...)
		if len(res.Edits) == 0 {
			return
		}
		out := apply(string(src), res.Edits)
		if again := process(name, []byte(out), opts.Titles, gen); len(again.Edits) > 0 {
			errs = append(errs, fmt.Errorf("%s: a second pass would edit again (%d edits): not written", name, len(again.Edits)))
			return
		}
		for _, e := range res.Edits {
			rep.bump(placeOf(name), e.Form, 1)
		}
		rep.Changed = append(rep.Changed, name)
		if opts.Write {
			if err := os.WriteFile(full, []byte(out), info.Mode().Perm()); err != nil {
				errs = append(errs, err)
			}
		}
	}

	paths := opts.Paths
	if len(paths) == 0 {
		paths = []string{"."}
	}
	for _, p := range paths {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		full := p
		if !filepath.IsAbs(p) {
			full = filepath.Join(opts.Root, p)
		}
		info, err := os.Stat(full)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		if !info.IsDir() {
			one(p)
			continue
		}
		walkErr := filepath.WalkDir(full, func(fp string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			rel, rerr := filepath.Rel(opts.Root, fp)
			if rerr != nil || filepath.IsAbs(p) {
				rel = fp
			}
			rel = citelint.UnderRoot(opts.Root, filepath.ToSlash(rel))
			if d.IsDir() {
				if citelint.SkipDir(rel) || citelint.Excluded(rel+"/", opts.Exclude) {
					return filepath.SkipDir
				}
				return nil
			}
			one(filepath.ToSlash(rel))
			return nil
		})
		if walkErr != nil {
			errs = append(errs, walkErr)
		}
	}
	sort.SliceStable(rep.Sites, func(i, j int) bool {
		a, b := rep.Sites[i], rep.Sites[j]
		if a.Path != b.Path {
			return a.Path < b.Path
		}
		if a.Line != b.Line {
			return a.Line < b.Line
		}
		return a.Kind < b.Kind
	})
	sort.Strings(rep.Changed)
	sort.Strings(rep.Deleted)
	return rep, errors.Join(errs...)
}

func (r *Report) bump(place string, f Form, n int) {
	if r.Edits[place] == nil {
		r.Edits[place] = map[Form]int{}
	}
	r.Edits[place][f] += n
}

var formNames = []struct {
	f    Form
	name string
}{
	{FormCodeComment, "1 code comment (enhancement NNNN)"},
	{FormText, "2 text (enhancement NNNN (\"title\"))"},
	{FormRetired, "3 retired id removed"},
	{FormPath, "4 path or site URL"},
	{FormDelete, "5 enhancement.yaml deleted"},
}

// WriteSummary prints the totals by place and form, and the worklist by
// place and kind.
func (r *Report) WriteSummary(w io.Writer, write bool) {
	verb := "would rewrite"
	if write {
		verb = "rewrote"
	}
	fmt.Fprintf(w, "enh cite-rewrite: %d files read, %d skipped\n", r.Files, r.Skipped)
	places := map[string]bool{}
	for p := range r.Edits {
		places[p] = true
	}
	for _, s := range r.Sites {
		places[placeOf(s.Path)] = true
	}
	var order []string
	for p := range places {
		order = append(order, p)
	}
	sort.Strings(order)
	total := map[Form]int{}
	fmt.Fprintf(w, "%s:\n", verb)
	for _, p := range order {
		for _, fn := range formNames {
			if n := r.Edits[p][fn.f]; n > 0 {
				fmt.Fprintf(w, "  %-14s form %-40s %6d\n", p, fn.name, n)
				total[fn.f] += n
			}
		}
	}
	sum := 0
	for _, fn := range formNames {
		if total[fn.f] > 0 {
			fmt.Fprintf(w, "  %-14s form %-40s %6d\n", "all", fn.name, total[fn.f])
		}
		sum += total[fn.f]
	}
	fmt.Fprintf(w, "  %d edits in %d files, %d files deleted\n", sum-total[FormDelete], len(r.Changed), len(r.Deleted))
	kinds := map[string]map[string]int{}
	allKinds := map[string]int{}
	for _, s := range r.Sites {
		p := placeOf(s.Path)
		if kinds[p] == nil {
			kinds[p] = map[string]int{}
		}
		kinds[p][s.Kind]++
		allKinds[s.Kind]++
	}
	fmt.Fprintf(w, "worklist (%d sites for an agent):\n", len(r.Sites))
	for _, p := range order {
		var ks []string
		for k := range kinds[p] {
			ks = append(ks, k)
		}
		sort.Strings(ks)
		for _, k := range ks {
			fmt.Fprintf(w, "  %-14s %-18s %6d\n", p, k, kinds[p][k])
		}
	}
	var ks []string
	for k := range allKinds {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	for _, k := range ks {
		fmt.Fprintf(w, "  %-14s %-18s %6d\n", "all", k, allKinds[k])
	}
}

// WriteWorklist writes one TSV row per site: path, line, kind, the line
// text and the decision title.
func (r *Report) WriteWorklist(w io.Writer) error {
	clean := func(s string) string {
		return strings.NewReplacer("\t", " ", "\n", " ", "\r", "").Replace(s)
	}
	if _, err := fmt.Fprintln(w, "path\tline\tkind\ttext\ttitle"); err != nil {
		return err
	}
	for _, s := range r.Sites {
		if _, err := fmt.Fprintf(w, "%s\t%d\t%s\t%s\t%s\n", s.Path, s.Line, s.Kind, clean(s.Text), clean(s.Title)); err != nil {
			return err
		}
	}
	return nil
}
