package index

import (
	"errors"
	"fmt"
	"sort"
	"strings"
)

const (
	kindAfter      = "after"
	kindSupersedes = "supersedes"
)

// edge goes from the entry that names the other to the other: for `after`, the
// later entry to the earlier one; for `supersedes`, the successor to the
// superseded entry.
type edge struct {
	kind, from, to string
}

// classDefs is the palette of the old GRAPH.md. `withdrawn` is new; `legacy`
// went with the `legacy:NNN` reference, which the new layout has no use for.
var classDefs = []string{
	"classDef draft       fill:#fef3c7,stroke:#b45309,color:#000",
	"classDef accepted    fill:#dbeafe,stroke:#1d4ed8,color:#000",
	"classDef rejected    fill:#fee2e2,stroke:#b91c1c,color:#7f1d1d,stroke-dasharray:4 2",
	"classDef withdrawn   fill:#fef2f2,stroke:#b91c1c,color:#7f1d1d,stroke-dasharray:1 3",
	"classDef superseded  fill:#e5e7eb,stroke:#6b7280,color:#6b7280",
	"classDef delivered   fill:#dcfce7,stroke:#15803d,color:#14532d",
	"classDef stub        fill:#f3f4f6,stroke:#9ca3af,color:#374151",
	"classDef category    fill:#ede9fe,stroke:#6d28d9,color:#000",
}

// Graphmd returns GRAPH.md: the category overview, one Mermaid diagram per
// category and the legend. `after` is a solid edge and `superseded_by` a thick
// one. A closed entry is drawn only where an edge from a live entry reaches
// it. It fails, and writes nothing, when an edge names an unknown entry.
func Graphmd(t *Tree) ([]byte, error) {
	edges, err := buildEdges(t)
	if err != nil {
		return nil, err
	}
	cat := map[string]string{}
	for _, e := range t.Entries {
		cat[e.ID] = e.Category
	}

	var b strings.Builder
	b.WriteString("# Enhancement Relationship Graph\n\n")
	b.WriteString("<!-- Generated by `task index` — do not edit by hand. -->\n\n")
	b.WriteString("Entries are partitioned by `config.yaml.category`, the type of work. The Overview\n")
	b.WriteString("shows how the categories lean on each other; each section shows one category\n")
	b.WriteString("with its foreign neighbours drawn as grey stubs. Closed entries (delivered,\n")
	b.WriteString("rejected, superseded, withdrawn) appear only where a live entry reaches them.\n\n")

	renderOverview(&b, t, edges, cat)
	for _, c := range Categories {
		renderCategory(&b, t, edges, cat, c)
	}
	renderLegend(&b)
	return []byte(b.String()), nil
}

func buildEdges(t *Tree) ([]edge, error) {
	known := map[string]*Entry{}
	for _, e := range t.Entries {
		known[e.ID] = e
	}
	var errs []error
	seen := map[edge]bool{}
	var all []edge
	add := func(kind, from, to, owner string) {
		if known[to] == nil || known[from] == nil {
			missing := to
			if known[to] != nil {
				missing = from
			}
			errs = append(errs, fmt.Errorf("entry %s names %s (%s), which is not an entry", owner, missing, kind))
			return
		}
		ed := edge{kind, from, to}
		if !seen[ed] {
			seen[ed] = true
			all = append(all, ed)
		}
	}
	for _, e := range t.Entries {
		for _, a := range e.After {
			add(kindAfter, e.ID, a, e.ID)
		}
		if e.Superseded != nil {
			for _, id := range e.Superseded.IDs {
				add(kindSupersedes, id, e.ID, e.ID)
			}
		}
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}
	sort.Slice(all, func(i, j int) bool {
		a, b := all[i], all[j]
		if a.kind != b.kind {
			return a.kind == kindAfter
		}
		if a.from != b.from {
			return a.from < b.from
		}
		return a.to < b.to
	})
	// An edge between two closed entries is history, not layering.
	var live []edge
	for _, ed := range all {
		if known[ed.from].Closed() && known[ed.to].Closed() {
			continue
		}
		live = append(live, ed)
	}
	return live, nil
}

func writeClassDefs(b *strings.Builder) {
	for _, c := range classDefs {
		b.WriteString("  " + c + "\n")
	}
}

func countLiveClosed(t *Tree, c string) (live, closed int) {
	for _, e := range t.Entries {
		if e.Category != c {
			continue
		}
		if e.Closed() {
			closed++
		} else {
			live++
		}
	}
	return live, closed
}

func renderOverview(b *strings.Builder, t *Tree, edges []edge, cat map[string]string) {
	cross := map[[2]string]int{}
	for _, ed := range edges {
		if ed.kind != kindAfter {
			continue
		}
		if a, c := cat[ed.from], cat[ed.to]; a != c {
			cross[[2]string{a, c}]++
		}
	}
	b.WriteString("## Overview\n\n")
	b.WriteString("One node per category, live and closed entry counts in the label. An edge label\n")
	b.WriteString("counts the `after` edges that cross from one category into another; edges\n")
	b.WriteString("inside a category are not shown here, and `superseded_by` is a lifecycle\n")
	b.WriteString("relation rather than layering, so it is left to the sections.\n\n")
	b.WriteString("```mermaid\ngraph LR\n")
	writeClassDefs(b)
	b.WriteString("\n")
	for _, c := range Categories {
		live, closed := countLiveClosed(t, c)
		word := "entries"
		if live == 1 {
			word = "entry"
		}
		if closed == 0 {
			fmt.Fprintf(b, "  C%s[\"%s (%d %s)\"]:::category\n", c, c, live, word)
		} else {
			fmt.Fprintf(b, "  C%s[\"%s (%d live %s, %d closed)\"]:::category\n", c, c, live, word, closed)
		}
	}
	b.WriteString("\n")
	for _, a := range Categories {
		for _, c := range Categories {
			if n := cross[[2]string{a, c}]; n > 0 {
				fmt.Fprintf(b, "  C%s -->|%d| C%s\n", a, n, c)
			}
		}
	}
	b.WriteString("```\n\n")
	if pairs := cyclePairs(cross); len(pairs) > 0 {
		fmt.Fprintf(b, "Mutually dependent categories (informational; the entry-level `after` graph stays acyclic, `task vet` enforces it): %s.\n\n", strings.Join(pairs, ", "))
	} else {
		b.WriteString("No category-level cycles.\n\n")
	}
}

// cyclePairs lists the category pairs that reach each other over the cross
// edges (transitive closure of five nodes).
func cyclePairs(cross map[[2]string]int) []string {
	n := len(Categories)
	reach := make([][]bool, n)
	for i := range reach {
		reach[i] = make([]bool, n)
	}
	for i, a := range Categories {
		for j, c := range Categories {
			if cross[[2]string{a, c}] > 0 {
				reach[i][j] = true
			}
		}
	}
	for k := 0; k < n; k++ {
		for i := 0; i < n; i++ {
			for j := 0; j < n; j++ {
				if reach[i][k] && reach[k][j] {
					reach[i][j] = true
				}
			}
		}
	}
	var out []string
	for i := 0; i < n; i++ {
		for j := i + 1; j < n; j++ {
			if reach[i][j] && reach[j][i] {
				out = append(out, Categories[i]+" ↔ "+Categories[j])
			}
		}
	}
	return out
}

func nodeLabel(e *Entry) string {
	title := strings.NewReplacer("`", "", "\"", "'", "\t", " ", "\n", " ", "\r", " ").Replace(e.Title)
	return e.ID + ": " + truncate(title, 50)
}

func renderCategory(b *strings.Builder, t *Tree, edges []edge, cat map[string]string, c string) {
	live, _ := countLiveClosed(t, c)
	fmt.Fprintf(b, "## %s\n\n", c)
	if live == 0 {
		b.WriteString("No live entries.\n\n")
		return
	}
	// Edges with at least one member endpoint, in either direction.
	var sec []edge
	hit := map[string]bool{}
	for _, ed := range edges {
		if cat[ed.from] == c || cat[ed.to] == c {
			sec = append(sec, ed)
			hit[ed.from], hit[ed.to] = true, true
		}
	}
	b.WriteString("```mermaid\ngraph TD\n")
	writeClassDefs(b)
	b.WriteString("\n")
	var members, stubs []string
	for _, e := range t.Entries {
		if e.Category != c {
			continue
		}
		if e.Closed() && !hit[e.ID] {
			continue
		}
		members = append(members, fmt.Sprintf("  N%s[\"%s\"]:::%s", e.ID, nodeLabel(e), e.Status))
	}
	stubSeen := map[string]bool{}
	for _, ed := range sec {
		for _, id := range []string{ed.from, ed.to} {
			if cat[id] != c && !stubSeen[id] {
				stubSeen[id] = true
				stubs = append(stubs, fmt.Sprintf("  N%s[\"%s · %s\"]:::stub", id, id, cat[id]))
			}
		}
	}
	sort.Strings(members)
	sort.Strings(stubs)
	for _, l := range members {
		b.WriteString(l + "\n")
	}
	for _, l := range stubs {
		b.WriteString(l + "\n")
	}
	b.WriteString("\n")
	for _, ed := range sec {
		if ed.kind == kindAfter {
			fmt.Fprintf(b, "  N%s -->|after| N%s\n", ed.from, ed.to)
		} else {
			fmt.Fprintf(b, "  N%s ==>|supersedes| N%s\n", ed.from, ed.to)
		}
	}
	b.WriteString("```\n\n")
}

func renderLegend(b *strings.Builder) {
	b.WriteString("## Legend\n\n```mermaid\ngraph LR\n")
	writeClassDefs(b)
	b.WriteString(`
  subgraph statuses ["Node statuses"]
    Ldraft["draft"]:::draft
    Laccepted["accepted"]:::accepted
    Lrejected["rejected"]:::rejected
    Lwithdrawn["withdrawn"]:::withdrawn
    Lsuperseded["superseded"]:::superseded
    Ldelivered["delivered"]:::delivered
  end

  subgraph other ["Other node kinds"]
    Lstub["NNNN · section (stub: lives in that section)"]:::stub
    Lcategory["section (n entries)"]:::category
  end

  subgraph edges ["Edge types"]
    Eaft_a["later"] -->|after| Eaft_b["earlier"]
    Esup_new["newer"] ==>|supersedes| Esup_old["older"]
    Ecat_a["category A"] -->|n| Ecat_b["category B"]
  end
` + "```\n\n")
	b.WriteString("A stub is an entry that lives in another section; its label names the section to jump to. `after` is a soft hint that an entry follows another; it blocks nothing. In the Overview, an edge label `n` counts the `after` edges crossing from A into B. Closed entries (delivered, rejected, superseded, withdrawn) appear only where a live entry's edge reaches them.\n")
}
