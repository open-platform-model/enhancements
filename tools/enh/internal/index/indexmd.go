package index

import (
	"fmt"
	"strings"
)

// Indexmd returns INDEX.md: the live table (the old-layout entries that are
// still live are in it until migration step M4), the archived table (the ten
// old-layout entries and every archived new-layout entry), the capability
// table and the status legend.
func Indexmd(t *Tree) []byte {
	var b strings.Builder
	b.WriteString("# Enhancement Index\n\n")
	b.WriteString("<!-- Generated by `task index` — do not edit by hand. -->\n\n")

	b.WriteString("| ID | Category | Affects | Status | Progress | Breaking | Title | Summary |\n")
	b.WriteString("| -- | -------- | ------- | ------ | -------- | -------- | ----- | ------- |\n")
	for _, e := range t.Entries {
		if e.Closed() {
			continue
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s |\n",
			link(e.ID, e.Dir), e.Category, cell(strings.Join(e.Affects, ", ")), e.Status,
			progress(e), breaking(e), cell(e.Title), cell(e.Summary))
	}

	b.WriteString("\n## Archived (delivered / rejected / superseded / withdrawn)\n\n")
	b.WriteString("| ID | Category | Status | Title | Summary | Why closed |\n")
	b.WriteString("| -- | -------- | ------ | ----- | ------- | ---------- |\n")
	for _, e := range t.Entries {
		if !e.Closed() {
			continue
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n",
			link(e.ID, e.Dir), e.Category, e.Status, cell(e.Title), cell(e.Summary), whyClosed(t, e))
	}

	b.WriteString("\n## Capabilities\n\n")
	if len(t.Capabilities) == 0 {
		b.WriteString("No capability yet. `openspec/specs/` fills when an entry or a seed is delivered.\n")
	} else {
		b.WriteString("| Capability | Requirements | Purpose |\n")
		b.WriteString("| ---------- | ------------ | ------- |\n")
		for _, c := range t.Capabilities {
			fmt.Fprintf(&b, "| [%s](./%s/%s/spec.md) | %d | %s |\n", cell(c.Name), specsDir, c.Name, c.Requirements, cell(c.Purpose))
		}
	}

	b.WriteString("\n## Status legend\n\n")
	b.WriteString("- **draft** — initial design, actively being written\n")
	b.WriteString("- **accepted** — design agreed upon, ready for implementation\n")
	b.WriteString("- **delivered** — every task shipped; the entry is archived and its requirements are in `openspec/specs/`\n")
	b.WriteString("- **rejected** — the idea was not accepted; the entry is archived with its reason\n")
	b.WriteString("- **superseded** — replaced by a newer enhancement; the entry is archived and `superseded_by` names the successor\n")
	b.WriteString("- **withdrawn** — the author stopped the work; the entry is archived with its reason\n")
	return []byte(b.String())
}

func link(id, dir string) string {
	return fmt.Sprintf("[%s](./%s/)", id, dir)
}

func progress(e *Entry) string {
	done, total := e.Counts()
	if total == 0 {
		return "-"
	}
	return fmt.Sprintf("%d of %d", done, total)
}

func breaking(e *Entry) string {
	switch {
	case e.Breaking == nil:
		return "-"
	case *e.Breaking:
		return "yes"
	}
	return "no"
}

// whyClosed is the last column of the archived table. The text of an old-layout
// entry is the old text of `task index`.
func whyClosed(t *Tree, e *Entry) string {
	switch e.Status {
	case StatusDelivered:
		if e.Layout == LayoutLegacy {
			if e.Landings == 0 {
				return "delivered"
			}
			return fmt.Sprintf("delivered %s (%d landings)", e.LandedOn, e.Landings)
		}
		_, total := e.Counts()
		return fmt.Sprintf("delivered %s (%d tasks)", e.ArchiveDate, total)
	case StatusSuperseded:
		if e.Superseded == nil {
			return "superseded"
		}
		var links []string
		for _, id := range e.Superseded.IDs {
			if succ := t.Entry(id); succ != nil {
				links = append(links, link(id, succ.Dir))
			} else {
				links = append(links, id)
			}
		}
		s := "superseded by " + joinIDs(links)
		if e.Superseded.Reason != "" {
			s += ": " + cell(e.Superseded.Reason)
		}
		return s
	case StatusRejected:
		switch {
		case e.Rejected != nil && e.Rejected.Reason != "":
			return cell(e.Rejected.Reason)
		case e.RejectedReason != "":
			return cell(e.RejectedReason)
		}
		return "-"
	case StatusWithdrawn:
		if e.Withdrawn != nil && e.Withdrawn.Reason != "" {
			return cell(e.Withdrawn.Reason)
		}
	}
	return "-"
}
