package index

import (
	"fmt"
	"path"
	"strings"
	"unicode/utf8"
)

const readmeHeader = "<!-- GENERATED by `task index` from config.yaml, proposal.md and tasks.md. Do not edit. -->"

// wordsPerMinute is the reading speed behind the Time column.
const wordsPerMinute = 250

// Readme returns the README.md of one new-layout entry (design T2.2 section 1):
// summary, status line, Read table, Progress and Still to do.
func Readme(e *Entry) []byte {
	var b strings.Builder
	b.WriteString(readmeHeader + "\n\n")
	fmt.Fprintf(&b, "# %s: %s\n\n", e.ID, e.Title)
	if e.Summary != "" {
		b.WriteString(e.Summary + "\n\n")
	}
	b.WriteString(statusLine(e) + "\n\n")
	if r := reasonLine(e); r != "" {
		b.WriteString(r + "\n\n")
	}

	type readRow struct{ file, learn, when string }
	var rows []readRow
	row := func(file, learn, when string) { rows = append(rows, readRow{file, learn, when}) }
	if e.ProposalWords > 0 {
		row("proposal.md", "What changes and why", readingTime(e.ProposalWords))
	}
	if e.DesignWords > 0 {
		row("design.md", "How it works, and why this way", readingTime(e.DesignWords))
	}
	if e.HasSpecs {
		row("specs/", "Exactly what must hold", "as needed")
	}
	if e.HasEvidence {
		row("evidence/", "The proof behind a claim", "as needed")
	}
	b.WriteString("## Read\n\n")
	if len(rows) == 0 {
		b.WriteString("Nothing to read yet.\n")
	} else {
		b.WriteString("| Step | File | You learn | Time |\n| --- | --- | --- | --- |\n")
		for i, r := range rows {
			fmt.Fprintf(&b, "| %d | [%s](%s) | %s | %s |\n", i+1, r.file, r.file, r.learn, r.when)
		}
	}
	b.WriteString("\n")

	if _, total := e.Counts(); total > 0 {
		b.WriteString("## Progress\n\n| Theme | Shipped |\n| --- | --- |\n")
		for _, s := range e.Tasks {
			if len(s.Tasks) == 0 {
				continue
			}
			done := 0
			for _, t := range s.Tasks {
				if t.Done {
					done++
				}
			}
			fmt.Fprintf(&b, "| %s | %d of %d |\n", cell(s.Title), done, len(s.Tasks))
		}
		b.WriteString("\n## Still to do\n\n")
		var repos []string
		open := map[string]int{}
		for _, s := range e.Tasks {
			for _, t := range s.Tasks {
				if t.Done {
					continue
				}
				if open[t.Repo] == 0 {
					repos = append(repos, t.Repo)
				}
				open[t.Repo]++
			}
		}
		if len(repos) == 0 {
			b.WriteString("Nothing. Every task is shipped.\n")
		} else {
			b.WriteString("| Repo | Open tasks |\n| --- | --- |\n")
			for _, r := range repos {
				fmt.Fprintf(&b, "| %s | %d |\n", cell(r), open[r])
			}
		}
		b.WriteString("\nThe list is [tasks.md](tasks.md).\n")
	}
	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}

func statusLine(e *Entry) string {
	var parts []string
	done, total := e.Counts()
	switch e.Status {
	case StatusDraft:
		parts = append(parts, "**Draft** "+e.Created)
	case StatusAccepted:
		parts = append(parts, "**Accepted** "+acceptedDate(e))
		switch {
		case total > 0 && done == total:
			parts = append(parts, "ready to deliver")
		case done > 0:
			parts = append(parts, "in progress")
		default:
			parts = append(parts, "ready to implement")
		}
	case StatusDelivered:
		parts = append(parts, "**Delivered** "+e.ArchiveDate)
	case StatusRejected:
		parts = append(parts, "**Rejected** "+endingDate(e.Rejected))
	case StatusWithdrawn:
		parts = append(parts, "**Withdrawn** "+endingDate(e.Withdrawn))
	case StatusSuperseded:
		s := "**Superseded**"
		if e.Superseded != nil {
			if e.Superseded.Date != "" {
				s += " " + e.Superseded.Date
			}
			s += " by " + joinIDs(e.Superseded.IDs)
		}
		parts = append(parts, s)
	}
	if total > 0 {
		parts = append(parts, fmt.Sprintf("%d of %d tasks shipped", done, total))
	}
	if e.Breaking != nil && *e.Breaking {
		parts = append(parts, "breaking")
	}
	return strings.Join(parts, " · ")
}

// reasonLine is the reason of an ending, on its own line under the status.
func reasonLine(e *Entry) string {
	var reason string
	switch e.Status {
	case StatusRejected:
		if e.Rejected != nil {
			reason = e.Rejected.Reason
		}
	case StatusWithdrawn:
		if e.Withdrawn != nil {
			reason = e.Withdrawn.Reason
		}
	case StatusSuperseded:
		if e.Superseded != nil {
			reason = e.Superseded.Reason
		}
	}
	if reason == "" {
		return ""
	}
	return "Reason: " + reason
}

func acceptedDate(e *Entry) string {
	date, _, _ := strings.Cut(e.Accepted, " ")
	return date
}

func endingDate(en *Ending) string {
	if en == nil {
		return ""
	}
	return en.Date
}

// joinIDs writes ids as "a", "a and b" or "a, b and c".
func joinIDs(ids []string) string {
	switch len(ids) {
	case 0:
		return ""
	case 1:
		return ids[0]
	}
	return strings.Join(ids[:len(ids)-1], ", ") + " and " + ids[len(ids)-1]
}

// readingTime rounds words / 250 to the nearest minute, at least one.
func readingTime(words int) string {
	m := (words + wordsPerMinute/2) / wordsPerMinute
	if m < 1 {
		m = 1
	}
	return fmt.Sprintf("%d min", m)
}

// cell makes text safe for a table cell.
func cell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

// truncate cuts s to max runes, ending in an ellipsis when it cuts.
func truncate(s string, max int) string {
	if utf8.RuneCountInString(s) <= max {
		return s
	}
	r := []rune(s)
	return string(r[:max-1]) + "…"
}

// readmePath is where the README.md of an entry lives.
func readmePath(e *Entry) string { return path.Join(e.Dir, "README.md") }
