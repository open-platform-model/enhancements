// want reads a .want file: one "LINE RULE" per line.
func readWant(t *testing.T, name string) []string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join("testdata", name))
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, l := range strings.Split(string(data), "\n") {
		if l = strings.TrimSpace(l); l != "" {
			out = append(out, l)
		}
	}
	sort.Strings(out)
	return out
}

func got(fs []Finding) []string {
	var out []string
	for _, f := range fs {
		out = append(out, strconv.Itoa(f.Line)+" "+f.Rule)
	}
	sort.Strings(out)
	return out
}

func equal(a, b []string) bool {
	return strings.Join(a, "\n") == strings.Join(b, "\n")
}

// TestFixtures lints each fixture under the name it would have in a repo.
// The fixtures end in .txt so that no real Go or CUE file holds a citation.
func TestFixtures(t *testing.T) {
	cases := []struct{ fixture, as, want string }{
		{"bad.go.txt", "bad.go", "bad.go.want"},
		{"bad.cue.txt", "bad.cue", "bad.cue.want"},
		{"ok.go.txt", "ok.go", "ok.go.want"},
		{"ok.cue.txt", "ok.cue", "ok.cue.want"},
	}
	for _, c := range cases {
		t.Run(c.fixture, func(t *testing.T) {
			src, err := os.ReadFile(filepath.Join("testdata", c.fixture))
			if err != nil {
				t.Fatal(err)
			}
			g, w := got(LintSource(c.as, src, Options{})), readWant(t, c.want)
			if !equal(g, w) {
				t.Errorf("findings of %s\n got: %q\nwant: %q", c.as, g, w)
			}
		})
	}
}

func TestOtherLanguageIsIgnored(t *testing.T) {
	if f := LintSource("README.md", []byte("0010"+":D1 is cited"), Options{}); len(f) != 0 {
		t.Fatalf("got findings for a Markdown file: %v", f)
	}
}

func TestSkipStrings(t *testing.T) {
	src := []byte("package p\n\nvar s = \"retired (0006" + ":D21)\"\n")
	if f := LintSource("a.go", src, Options{}); len(f) != 1 || f[0].Rule != RuleDecisionNumber || f[0].Line != 3 {
		t.Fatalf("with strings: %v", f)
	}
	if f := LintSource("a.go", src, Options{SkipStrings: true}); len(f) != 0 {
		t.Fatalf("without strings: %v", f)
	}
}

func TestDecisionNumberForms(t *testing.T) {
	for _, tc := range []struct {
		text string
		n    int
	}{
		{"// 0010" + ":D1", 1},
		{"// 0016" + ":D5:R5", 1},
		{"// 0021" + ":OQ7", 1},
		{"// 0010" + ":D4; 0010" + ":D44.", 2},
		{"// see 0006" + ":D21/OQ12", 1},
		{"// (enhancement 0010)", 0},
		{"// at 10:30 and 20260" + ":D1", 0},
		{"// 0010:Dx", 0},
	} {
		src := []byte("package p\n" + tc.text + "\nvar _ = 1\n")
		n := 0
		for _, f := range LintSource("a.go", src, Options{}) {
			if f.Rule == RuleDecisionNumber {
				n++
			}
		}
		if n != tc.n {
			t.Errorf("%q: %d decision-number findings, want %d", tc.text, n, tc.n)
		}
	}
}

func TestFindingMessage(t *testing.T) {
	f := LintSource("x.go", []byte("package p\n\n// (0010"+":D1)\nvar _ = 1\n"), Options{})
	if len(f) == 0 || !strings.HasPrefix(f[0].String(), "x.go:3: decision-number: ") {
		t.Fatalf("string form: %v", f)
	}
}

func write(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestLintFiles(t *testing.T) {
	root := t.TempDir()
	write(t, root, "a/bad.go", "package a\n\n// 0010"+":D1\nvar _ = 1\n")
	write(t, root, "a/ok.go", "package a\n\n// Reason in words (enhancement 0010).\nvar _ = 1\n")
	write(t, root, "a/gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage a\n\n// 0010"+":D1\nvar _ = 2\n")
	write(t, root, "b/frozen/old.cue", "// 0010"+":D1\n")
	write(t, root, "b/new.cue", "// WHY fqn: 0010.\n")
	write(t, root, "c/readme.md", "0010"+":D1\n")
	write(t, root, "vendor/v.go", "package v\n\n// 0010"+":D1\nvar _ = 3\n")
	write(t, root, "cue.mod/pkg/p.cue", "// 0010"+":D1\n")

	t.Run("directory walk with exclusion", func(t *testing.T) {
		res, err := LintFiles(root, []string{"."}, Options{Exclude: []string{"frozen/"}})
		if err != nil {
			t.Fatal(err)
		}
		// a/bad.go breaks two rules (decision-number, lone-id); b/new.cue one.
		if len(res.Findings) != 3 {
			t.Fatalf("findings: %v", res.Findings)
		}
		if res.Findings[0].Path != "a/bad.go" || res.Findings[2].Path != "b/new.cue" {
			t.Errorf("paths: %v", res.Findings)
		}
		if res.Checked != 3 {
			t.Errorf("checked %d files, want 3 (bad.go, ok.go, new.cue)", res.Checked)
		}
	})

	t.Run("path list", func(t *testing.T) {
		res, err := LintFiles(root, []string{"a/ok.go", "a/gen.go", "c/readme.md"}, Options{})
		if err != nil || len(res.Findings) != 0 || res.Checked != 1 || res.Skipped != 2 {
			t.Fatalf("res=%+v err=%v", res, err)
		}
	})

	t.Run("missing path is an error", func(t *testing.T) {
		if _, err := LintFiles(root, []string{"a/none.go"}, Options{}); err == nil {
			t.Fatal("want an error for a path that does not exist")
		}
	})

	t.Run("git file list", func(t *testing.T) {
		for _, list := range []string{"a/bad.go\nb/new.cue\nc/readme.md\n", "a/bad.go\x00b/new.cue\x00c/readme.md\x00"} {
			paths, err := ReadFileList(strings.NewReader(list))
			if err != nil || len(paths) != 3 {
				t.Fatalf("paths=%q err=%v", paths, err)
			}
			res, err := LintFiles(root, paths, Options{})
			if err != nil || len(res.Findings) != 3 {
				t.Fatalf("res=%+v err=%v", res, err)
			}
		}
	})
}

func TestGeneratedFixture(t *testing.T) {
	src, err := os.ReadFile(filepath.Join("testdata", "generated.go.txt"))
	if err != nil {
		t.Fatal(err)
	}
	if !isGenerated(src) {
		t.Fatal("generated header not detected")
	}
	if isGenerated([]byte("package p\n\n// Code generated by x. DO NOT EDIT.\n")) {
		t.Fatal("a header after the package clause is not a generated marker")
	}
}

func TestWalkSkipsCachesAndWorktrees(t *testing.T) {
	root := t.TempDir()
	write(t, root, ".cue-cache/mod/x.cue", "// 0010"+":D1\n")
	write(t, root, ".claude/worktrees/w/x.cue", "// 0010"+":D1\n")
	res, err := LintFiles(root, []string{"."}, Options{})
	if err != nil || len(res.Findings) != 0 || res.Checked != 0 {
		t.Fatalf("res=%+v err=%v", res, err)
	}
}
