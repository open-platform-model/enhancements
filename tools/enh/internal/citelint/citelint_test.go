// want reads a .want file: one "LINE RULE" per line.
func readWant(t *testing.T, name string) []string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join("testdata", name))
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, l := range strings.Split(string(data), "\n") {
		if l = strings.TrimSpace(l); l != "" {
			out = append(out, l)
		}
	}
	sort.Strings(out)
	return out
}

func got(fs []Finding) []string {
	var out []string
	for _, f := range fs {
		out = append(out, strconv.Itoa(f.Line)+" "+f.Rule)
	}
	sort.Strings(out)
	return out
}

func equal(a, b []string) bool {
	return strings.Join(a, "\n") == strings.Join(b, "\n")
}

// TestFixtures lints each fixture under the name it would have in a repo.
// The fixtures end in .txt so that no real Go or CUE file holds a citation.
func TestFixtures(t *testing.T) {
	cases := []struct{ fixture, as, want string }{
		{"bad.go.txt", "bad.go", "bad.go.want"},
		{"bad.cue.txt", "bad.cue", "bad.cue.want"},
		{"ok.go.txt", "ok.go", "ok.go.want"},
		{"ok.cue.txt", "ok.cue", "ok.cue.want"},
	}
	for _, c := range cases {
		t.Run(c.fixture, func(t *testing.T) {
			src, err := os.ReadFile(filepath.Join("testdata", c.fixture))
			if err != nil {
				t.Fatal(err)
			}
			g, w := got(LintSource(c.as, src, Options{})), readWant(t, c.want)
			if !equal(g, w) {
				t.Errorf("findings of %s\n got: %q\nwant: %q", c.as, g, w)
			}
		})
	}
}

