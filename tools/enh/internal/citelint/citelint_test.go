func write(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestLintFiles(t *testing.T) {
	root := t.TempDir()
	write(t, root, "a/bad.go", "package a\n\n// 0010"+":D1\nvar _ = 1\n")
	write(t, root, "a/ok.go", "package a\n\n// Reason in words (enhancement 0010).\nvar _ = 1\n")
	write(t, root, "a/gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage a\n\n// 0010"+":D1\nvar _ = 2\n")
	write(t, root, "b/frozen/old.cue", "// 0010"+":D1\n")
	write(t, root, "b/new.cue", "// WHY fqn: 0010.\n")
	write(t, root, "c/readme.md", "0010"+":D1\n")
	write(t, root, "vendor/v.go", "package v\n\n// 0010"+":D1\nvar _ = 3\n")
	write(t, root, "cue.mod/pkg/p.cue", "// 0010"+":D1\n")

	t.Run("directory walk with exclusion", func(t *testing.T) {
		res, err := LintFiles(root, []string{"."}, Options{Exclude: []string{"frozen/"}})
		if err != nil {
			t.Fatal(err)
		}
		// a/bad.go breaks two rules (decision-number, lone-id); b/new.cue one.
		if len(res.Findings) != 3 {
			t.Fatalf("findings: %v", res.Findings)
		}
		if res.Findings[0].Path != "a/bad.go" || res.Findings[2].Path != "b/new.cue" {
			t.Errorf("paths: %v", res.Findings)
		}
		if res.Checked != 3 {
			t.Errorf("checked %d files, want 3 (bad.go, ok.go, new.cue)", res.Checked)
		}
	})

	t.Run("path list", func(t *testing.T) {
		res, err := LintFiles(root, []string{"a/ok.go", "a/gen.go", "c/readme.md"}, Options{})
		if err != nil || len(res.Findings) != 0 || res.Checked != 1 || res.Skipped != 2 {
			t.Fatalf("res=%+v err=%v", res, err)
		}
	})

	t.Run("missing path is an error", func(t *testing.T) {
		if _, err := LintFiles(root, []string{"a/none.go"}, Options{}); err == nil {
			t.Fatal("want an error for a path that does not exist")
		}
	})

	t.Run("git file list", func(t *testing.T) {
		for _, list := range []string{"a/bad.go\nb/new.cue\nc/readme.md\n", "a/bad.go\x00b/new.cue\x00c/readme.md\x00"} {
			paths, err := ReadFileList(strings.NewReader(list))
			if err != nil || len(paths) != 3 {
				t.Fatalf("paths=%q err=%v", paths, err)
			}
			res, err := LintFiles(root, paths, Options{})
			if err != nil || len(res.Findings) != 3 {
				t.Fatalf("res=%+v err=%v", res, err)
			}
		}
	})
}

